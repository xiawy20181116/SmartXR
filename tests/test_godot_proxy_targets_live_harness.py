        self.assertIn('"depth_confidence": _last_depth_confidence', source)
        self.assertIn('"ws_state": _ws.get_ready_state()', source)
        self.assertIn('"connect_attempts": _connect_attempts', source)
        self.assertIn('"last_connect_error": _last_connect_error', source)
        self.assertIn('"parsed": _parsed', source)
        self.assertIn('"live": _live', source)
        self.assertIn("quit(0)", source)
        self.assertIn("quit(1)", source)

        self.assertNotIn("OpenXR", source)
        self.assertNotIn("XRServer", source)
        self.assertNotIn("XROrigin", source)

