        self.assertIn('_load_script_from_env("PROXY_TARGETS_CARD_ADAPTER_SCRIPT"', source)
        self.assertNotIn('preload("res://scripts/proxy_targets_consumer.gd")', source)
        self.assertNotIn('preload("res://scripts/proxy_targets_card_adapter.gd")', source)
        self.assertIn("WebSocketPeer.new()", source)
        self.assertIn("_connect_attempts", source)
        self.assertIn("_last_connect_error", source)
        self.assertIn("connect_to_url(_ws_url)", source)
